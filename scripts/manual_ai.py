def main():
    p = os.path.join(ROOT, "data", "news.json")
    with open(p, encoding="utf-8") as f:
        d = json.load(f)
    n = 0
    for post in d["posts"]:
        if post["id"] in SUMMARIES and not post.get("ai"):
            a = SUMMARIES[post["id"]]
            k = len(post.get("images") or [])
            for pt in a["points"]:
                if pt["img"] and pt["img"] > k:
                    pt["img"] = None
            post["ai"] = a
            n += 1
    with open(p, "w", encoding="utf-8") as f:
        json.dump(d, f, ensure_ascii=False, indent=1)
    print("merged", n)


if __name__ == "__main__":
    main()
